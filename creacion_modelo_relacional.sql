-- =============================================================================
-- SISTEMA DE GESTIÓN INTEGRAL PARA CENTROS GERIÁTRICOS (SAMANYA OS)
-- SCRIPT DE CREACIÓN DE BASE DE DATOS RELACIONAL - ORACLE DATABASE
-- =============================================================================
-- Prefijo de tablas: SMY_
-- Estándar: Oracle 11g / 12c / 19c / 21c / 23c
-- Reglas de Nomenclatura y Arquitectura:
--  1. Todas las tablas poseen 'ID NUMBER(10)' como Clave Primaria poblada
--     automáticamente mediante Secuencias y Triggers BEFORE INSERT.
--  2. Todas las llaves foráneas inician obligatoriamente con 'ID_' (ej. ID_ROL, ID_USUARIO, ID_RESIDENTE).
--  3. Todos los estados y opciones categóricas poseen tablas maestras foráneas (SMY_ESTADOS_*, SMY_TIPOS_*, etc.).
--  4. Todas las fechas por defecto registran la hora legal de Bogotá, Colombia (UTC-5):
--     DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE).
--  5. Todas las tablas contienen 'FECHA_CREACION DATE' e 'ID_USUARIO_ULTIMA_MODIFICACION NUMBER(10)'.
--  6. Campos booleanos se manejan como CHAR(1) con validación ('S', 'N').
-- =============================================================================

-- =============================================================================
-- SECCIÓN 0: TABLAS MAESTRAS Y CATÁLOGOS FORÁNEOS (LOOKUPS)
-- =============================================================================

-- 0.1 Estados de Roles
CREATE TABLE SMY_ESTADOS_ROLES (
    ID                              NUMBER(10)      NOT NULL,
    NOMBRE_ESTADO_ROL               VARCHAR2(50)    NOT NULL,
    FECHA_CREACION                  DATE            DEFAULT CAST(SYSTIMESTAMP AT TIME ZONE '-05:00' AS DATE) NOT NULL,
    ID_USUARIO_ULTIMA_MODIFICACION  NUMBER(10),
    CONSTRAINT PK_SMY_ESTADOS_ROLES PRIMARY KEY (ID),
    CONSTRAINT UQ_SMY_EST_ROL_NOM UNIQUE (NOMBRE_ESTADO_ROL)
);
CREATE SEQUENCE SEQ_SMY_ESTADOS_ROLES START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE OR REPLACE TRIGGER TRG_SMY_ESTADOS_ROLES_BI
BEFORE INSERT ON SMY_ESTADOS_ROLES FOR EACH ROW
BEGIN
    IF :NEW.ID IS NULL THEN SELECT SEQ_SMY_ESTADOS_ROLES.NEXTVAL INTO :NEW.ID FROM DUAL; END IF;
END;
/

